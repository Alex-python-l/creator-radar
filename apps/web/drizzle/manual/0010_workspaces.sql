-- Personal + team workspaces. Additive and idempotent: legacy ownership
-- columns/tables remain until the compatibility window closes.

CREATE TABLE IF NOT EXISTS organizations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  logo text,
  metadata text,
  monitor_quota integer NOT NULL DEFAULT 20,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS members (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'member',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT members_role_check CHECK (role IN ('owner', 'admin', 'member'))
);
CREATE UNIQUE INDEX IF NOT EXISTS members_user_uq ON members(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS members_org_user_uq ON members(organization_id, user_id);
CREATE INDEX IF NOT EXISTS members_organization_idx ON members(organization_id);
CREATE UNIQUE INDEX IF NOT EXISTS members_one_owner_per_org_uq
  ON members(organization_id) WHERE role = 'owner';

CREATE TABLE IF NOT EXISTS invitations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  email text NOT NULL,
  role text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  expires_at timestamptz NOT NULL,
  inviter_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT invitations_role_check CHECK (role IN ('admin', 'member'))
);
CREATE INDEX IF NOT EXISTS invitations_organization_idx ON invitations(organization_id);
CREATE INDEX IF NOT EXISTS invitations_email_idx ON invitations(lower(email));

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS active_organization_id integer;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'sessions_active_organization_fk'
  ) THEN
    ALTER TABLE sessions ADD CONSTRAINT sessions_active_organization_fk
      FOREIGN KEY (active_organization_id) REFERENCES organizations(id) ON DELETE SET NULL;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS workspaces (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL,
  user_id integer REFERENCES users(id) ON DELETE CASCADE,
  organization_id integer REFERENCES organizations(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT workspaces_kind_check CHECK (kind IN ('personal', 'team')),
  CONSTRAINT workspaces_owner_check CHECK (
    (kind = 'personal' AND user_id IS NOT NULL AND organization_id IS NULL) OR
    (kind = 'team' AND user_id IS NULL AND organization_id IS NOT NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS workspaces_user_uq ON workspaces(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS workspaces_organization_uq ON workspaces(organization_id);

INSERT INTO workspaces(kind, user_id)
SELECT 'personal', u.id FROM users u
ON CONFLICT (user_id) DO NOTHING;

-- One-time security flip: all legacy accounts must prove control of a real
-- mailbox, and every pre-workspace session is revoked. A marker keeps reruns
-- idempotent so verified users are not reset again.
CREATE TABLE IF NOT EXISTS manual_migration_markers (
  name text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM manual_migration_markers
    WHERE name = '0010_workspace_email_reverify'
  ) THEN
    UPDATE users SET email_verified = false, updated_at = now();
    DELETE FROM sessions;
    INSERT INTO manual_migration_markers(name)
    VALUES ('0010_workspace_email_reverify');
  END IF;
END $$;

ALTER TABLE account_groups ADD COLUMN IF NOT EXISTS workspace_id integer;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'account_groups_workspace_fk'
  ) THEN
    ALTER TABLE account_groups ADD CONSTRAINT account_groups_workspace_fk
      FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS account_groups_workspace_idx ON account_groups(workspace_id);

UPDATE account_groups g
SET workspace_id = w.id
FROM workspaces w
WHERE g.workspace_id IS NULL AND g.owner_id = w.user_id AND w.kind = 'personal';

INSERT INTO account_groups(name, owner_id, workspace_id, sort_order)
SELECT '未分组', w.user_id, w.id, 0
FROM workspaces w
WHERE w.kind = 'personal'
  AND NOT EXISTS (
    SELECT 1 FROM account_groups g WHERE g.workspace_id = w.id
  );

CREATE TABLE IF NOT EXISTS workspace_influencers (
  workspace_id integer NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  influencer_id integer NOT NULL REFERENCES influencers(id) ON DELETE CASCADE,
  group_id integer,
  alias text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (workspace_id, influencer_id)
);
CREATE INDEX IF NOT EXISTS workspace_influencers_influencer_idx
  ON workspace_influencers(influencer_id);
CREATE INDEX IF NOT EXISTS workspace_influencers_workspace_group_idx
  ON workspace_influencers(workspace_id, group_id);

INSERT INTO workspace_influencers(workspace_id, influencer_id, group_id, alias, created_at)
SELECT w.id, ui.influencer_id, ui.group_id, ui.alias, ui.created_at
FROM user_influencers ui
JOIN workspaces w ON w.kind = 'personal' AND w.user_id = ui.user_id
ON CONFLICT (workspace_id, influencer_id) DO UPDATE
SET group_id = EXCLUDED.group_id, alias = EXCLUDED.alias;

-- Names are now unique inside a workspace. Legacy indexes stay until the
-- bootstrap team migration has assigned owner_id IS NULL rows.
CREATE UNIQUE INDEX IF NOT EXISTS account_groups_workspace_name_uq
  ON account_groups(workspace_id, name) WHERE workspace_id IS NOT NULL;
