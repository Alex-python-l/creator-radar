-- 多用户面向公众(2026-07-17 设计):better-auth 认证四表 + 订阅制隔离。
-- 幂等,可重复执行。上线顺序:先跑本文件 → 跑 scripts/migrate-users-to-radar.mjs
-- (mkt.users → users+accounts, role=admin) → 部署 web → 部署 studio。
--
-- users/sessions/accounts/verifications 形状 = better-auth CLI generate 输出
-- (usePlural + serial id + username/admin 插件 + monitorQuota 附加字段),
-- 列类型按库内惯例用 timestamptz。业务侧勿直接写这四张表(迁移脚本除外)。

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  email_verified boolean NOT NULL DEFAULT false,
  image text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  username text UNIQUE,
  display_username text,
  role text,
  banned boolean DEFAULT false,
  ban_reason text,
  ban_expires timestamptz,
  monitor_quota integer
);

CREATE TABLE IF NOT EXISTS sessions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expires_at timestamptz NOT NULL,
  token text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  ip_address text,
  user_agent text,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  impersonated_by text
);

CREATE INDEX IF NOT EXISTS "sessions_userId_idx" ON sessions (user_id);

CREATE TABLE IF NOT EXISTS accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id text NOT NULL,
  provider_id text NOT NULL,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  access_token text,
  refresh_token text,
  id_token text,
  access_token_expires_at timestamptz,
  refresh_token_expires_at timestamptz,
  scope text,
  password text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "accounts_userId_idx" ON accounts (user_id);

CREATE TABLE IF NOT EXISTS verifications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identifier text NOT NULL,
  value text NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS verifications_identifier_idx ON verifications (identifier);

-- ============ 业务侧:订阅制隔离 ============

-- 分组归属:NULL=系统组(admin 全局视图),非 NULL=普通用户私有组。
ALTER TABLE account_groups ADD COLUMN IF NOT EXISTS owner_id integer;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'account_groups_owner_fk'
  ) THEN
    ALTER TABLE account_groups
      ADD CONSTRAINT account_groups_owner_fk
      FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS account_groups_owner_idx ON account_groups (owner_id);

-- 组名唯一从全局改为按 owner:系统组之间仍全局唯一;用户组在各自名下唯一。
-- (owner_id,name) 复合唯一对 NULL owner 不生效(NULL 互不冲突),故系统组单独一条 partial。
ALTER TABLE account_groups DROP CONSTRAINT IF EXISTS account_groups_name_key;
ALTER TABLE account_groups DROP CONSTRAINT IF EXISTS account_groups_name_unique;
CREATE UNIQUE INDEX IF NOT EXISTS account_groups_system_name_uq
  ON account_groups (name) WHERE owner_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS account_groups_owner_name_uq
  ON account_groups (owner_id, name) WHERE owner_id IS NOT NULL;

-- 普通用户 ↔ 监控账号订阅关系。influencers/videos 全局一份,
-- group_id/alias 是订阅者私有视图属性(group_id 弱引用,应用层保证 owner 一致)。
CREATE TABLE IF NOT EXISTS user_influencers (
  user_id integer NOT NULL,
  influencer_id integer NOT NULL,
  group_id integer,
  alias text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, influencer_id),
  CONSTRAINT user_influencers_user_fk
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT user_influencers_influencer_fk
    FOREIGN KEY (influencer_id) REFERENCES influencers(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS user_influencers_influencer_idx
  ON user_influencers (influencer_id);
CREATE INDEX IF NOT EXISTS user_influencers_user_group_idx
  ON user_influencers (user_id, group_id);
